import { test, expect } from '@playwright/test';
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { fx, trackExternalRequests, expectNoConsoleErrors } from './helpers';

/** Small CRC-32 so the hand-built test archive is valid. */
function crc32(buf: Buffer) {
  let c = ~0;
  for (const b of buf) {
    c ^= b;
    for (let k = 0; k < 8; k++) c = (c >>> 1) ^ (0xedb88320 & -(c & 1));
  }
  return ~c >>> 0;
}

/** Builds a one-entry, stored (method 0) zip. flags: general-purpose bit flag (bit 0 = encrypted, bit 11 = UTF-8). */
function buildZip(nameBytes: Buffer, data: Buffer, flags: number) {
  const crc = crc32(data);
  const local = Buffer.alloc(30);
  local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(flags, 6); local.writeUInt16LE(0, 8);
  local.writeUInt32LE(crc, 14); local.writeUInt32LE(data.length, 18); local.writeUInt32LE(data.length, 22); local.writeUInt16LE(nameBytes.length, 26);
  const central = Buffer.alloc(46);
  central.writeUInt32LE(0x02014b50, 0); central.writeUInt16LE(20, 4); central.writeUInt16LE(20, 6); central.writeUInt16LE(flags, 8);
  central.writeUInt32LE(crc, 16); central.writeUInt32LE(data.length, 20); central.writeUInt32LE(data.length, 24); central.writeUInt16LE(nameBytes.length, 28);
  central.writeUInt32LE(0, 42);
  const cdOffset = local.length + nameBytes.length + data.length;
  const eocd = Buffer.alloc(22);
  eocd.writeUInt32LE(0x06054b50, 0); eocd.writeUInt16LE(1, 8); eocd.writeUInt16LE(1, 10);
  eocd.writeUInt32LE(central.length + nameBytes.length, 12); eocd.writeUInt32LE(cdOffset, 16);
  return Buffer.concat([local, nameBytes, data, central, nameBytes, eocd]);
}

test.describe('Zip Files (EN)', () => {
  test('creates a zip from two files, then extracts the same zip; no external requests', async ({ page }, testInfo) => {
    test.setTimeout(90_000);
    const external = trackExternalRequests(page);
    const noErrors = await expectNoConsoleErrors(page);
    await page.goto('/en/zip-files/');

    // Fixtures may be regenerated by a parallel test run; work on copies.
    const pdfPath = testInfo.outputPath('iki-sayfa.pdf');
    const pngPath = testInfo.outputPath('fotoğraf-ş.png');
    copyFileSync(fx('iki-sayfa.pdf'), pdfPath);
    copyFileSync(fx('fotoğraf-ş.png'), pngPath);

    // --- Create
    await page.locator('#drop-create input[type=file]').setInputFiles([pdfPath, pngPath]);
    await expect(page.locator('#files-create li')).toHaveCount(2);
    await expect(page.locator('#summary-create')).toContainText('2 files');
    await page.locator('#opt-name').fill('my-archive');
    await page.locator('#opt-level').selectOption('6');
    await page.locator('#create').click();
    // Deflate runs in a Web Worker; allow extra time when the machine is busy
    await expect(page.locator('#result-create')).toHaveClass(/is-active/, { timeout: 30_000 });
    await expect(page.locator('#result-info-create')).toContainText('2 files');
    const [dl] = await Promise.all([page.waitForEvent('download'), page.locator('#download-create').click()]);
    expect(dl.suggestedFilename()).toBe('my-archive.zip');
    const zipPath = testInfo.outputPath('my-archive.zip');
    copyFileSync((await dl.path())!, zipPath);
    expect(readFileSync(zipPath).subarray(0, 2).toString()).toBe('PK');

    // --- Extract
    await page.getByRole('tab', { name: 'Extract zip' }).click();
    await expect(page.locator('#panel-extract')).toBeVisible();
    await page.locator('#drop-extract input[type=file]').setInputFiles(zipPath);
    await expect(page.locator('#entries li')).toHaveCount(2);
    await expect(page.locator('#entries')).toContainText('iki-sayfa.pdf');
    await expect(page.locator('#entries')).toContainText('fotoğraf-ş.png');
    await expect(page.locator('#summary-extract')).toContainText('2 files');
    // The UTF-8 flag is written, so the encoding picker must stay hidden
    await expect(page.locator('#enc-field')).toBeHidden();

    // Download one file: content must be byte-identical to the original
    const [one] = await Promise.all([
      page.waitForEvent('download'),
      page.locator('#entries button[data-entry]').filter({ hasText: 'Download' }).nth(1).click(),
    ]);
    expect(one.suggestedFilename()).toBe('fotoğraf-ş.png');
    expect(Buffer.compare(readFileSync((await one.path())!), readFileSync(fx('fotoğraf-ş.png')))).toBe(0);

    expect(external).toEqual([]);
    noErrors();
  });

  test('legacy archive without the UTF-8 flag: names decode as CP437 and the encoding menu can change them', async ({ page }, testInfo) => {
    await page.goto('/en/zip-files/#extract');
    await expect(page.locator('#panel-extract')).toBeVisible();
    // 0x82 is "é" in DOS CP437 and "‚" (low quote) in Windows-1252
    const legacy = testInfo.outputPath('legacy.zip');
    writeFileSync(legacy, buildZip(Buffer.from([0x63, 0x61, 0x66, 0x82, 0x2e, 0x74, 0x78, 0x74]), Buffer.from('hello'), 0));
    await page.locator('#drop-extract input[type=file]').setInputFiles(legacy);
    await expect(page.locator('#enc-field')).toBeVisible();
    await expect(page.locator('#entries')).toContainText('café.txt');
    await page.locator('#opt-encoding').selectOption('windows-1252');
    await expect(page.locator('#entries')).toContainText('caf‚.txt');
    await page.locator('#opt-encoding').selectOption('cp437');
    await expect(page.locator('#entries')).toContainText('café.txt');
    const [dl] = await Promise.all([page.waitForEvent('download'), page.locator('#entries button[data-entry]').first().click()]);
    expect(dl.suggestedFilename()).toBe('café.txt');
    expect(readFileSync((await dl.path())!).toString()).toBe('hello');
  });

  test('encrypted zip, non-zip file and RAR give clear English errors', async ({ page }, testInfo) => {
    await page.goto('/en/zip-files/#extract');
    await expect(page.locator('#panel-extract')).toBeVisible();

    // Hand-built zip whose general-purpose flag has the encryption bit (bit 0) set
    const encPath = testInfo.outputPath('encrypted.zip');
    writeFileSync(encPath, buildZip(Buffer.from('secret.txt'), Buffer.from('abcdef'), 1));
    await page.locator('#drop-extract input[type=file]').setInputFiles(encPath);
    await expect(page.locator('#error-extract')).toContainText('Password-protected zip files are not supported');
    await expect(page.locator('#entries li')).toHaveCount(0);

    // A file that is not a zip
    await page.locator('#drop-extract input[type=file]').setInputFiles(fx('bozuk.pdf'));
    await expect(page.locator('#error-extract')).toContainText(/damaged or is not a valid zip/);

    // RAR extension: the limitation is stated plainly
    const rarPath = testInfo.outputPath('sample.rar');
    writeFileSync(rarPath, 'Rar!\x1a\x07\x00');
    await page.locator('#drop-extract input[type=file]').setInputFiles(rarPath);
    await expect(page.locator('#error-extract')).toContainText(/RAR/);
  });

  test('page integrity: English metadata, badge, 3 ads outside the tool box, 800+ words, 6+ FAQ, related links resolve', async ({ page }) => {
    await page.goto('/en/zip-files/');
    expect(await page.locator('html').getAttribute('lang')).toBe('en');
    await expect(page.locator('link[rel=canonical]')).toHaveAttribute('href', 'https://araclar.bilisimajans.com/en/zip-files/');
    await expect(page.locator('link[hreflang=tr]')).toHaveAttribute('href', 'https://araclar.bilisimajans.com/zip/');
    await expect(page.locator('.ba-badges')).toContainText('Files never leave your device');
    expect(await page.locator('.ba-tool .ba-ad').count()).toBe(0);
    expect(await page.locator('.ba-ad').count()).toBe(3);
    expect(await page.locator('.ba-faq details').count()).toBeGreaterThanOrEqual(6);
    await expect(page.locator('.ba-related a[href="../"]')).toBeVisible();
    const words = (await page.locator('.ba-content').evaluate((el) => el.textContent || '')).split(/\s+/).filter(Boolean).length;
    expect(words).toBeGreaterThanOrEqual(800);
    const hrefs = await page.locator('.ba-related a').evaluateAll((as) => as.map((a) => (a as HTMLAnchorElement).href));
    for (const href of hrefs) {
      const res = await page.request.get(href);
      expect(res.status(), href).toBe(200);
    }
  });
});
